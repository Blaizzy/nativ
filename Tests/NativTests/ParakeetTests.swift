            XCTAssertEqual(padded.count, 3000 * 128)
            XCTAssertEqual(padded[0], Float(window.startFrame + 1))
            XCTAssertEqual(padded[window.validFrames * 128 - 1], Float(window.startFrame + window.validFrames))
            XCTAssertTrue(padded[(window.validFrames * 128)...].allSatisfy { $0 == 0 })
        }
    }

    func testFixedEncoderLengthsAndPositionsAreRepresentableInFP16() throws {
        for length in 2...3000 {
            let lengths = ParakeetChunkPlan.subsampledLengths(validFrames: length)
            XCTAssertEqual(lengths.map(Int.init), [(length + 1) / 2, (length + 3) / 4, (length + 7) / 8])
        }
        // Only even positions survive the first stride-2 convolution. Odd
        // positions above 2048 round in FP16, but every used position is exact.
        for index in stride(from: 0, to: 3000, by: 2) {
            XCTAssertEqual(Int(Float16(index)), index)
        }
        let metadata = try configuration().metadata
        XCTAssertEqual(metadata.encoderFrames, 3000)
        XCTAssertEqual(metadata.encoderDtype, "fp16")
        XCTAssertEqual(ParakeetDecoder.positionalEmbeddings(totalFrames: 3000, metadata: metadata).count, 749 * 1024)
    }

    func testAutomaticSelectionHonorsExplicitModels() {
        XCTAssertEqual(DefaultSpeechModel.isPreferred(selectedModelID: nil), DefaultSpeechModel.isSupported)
        XCTAssertFalse(DefaultSpeechModel.isPreferred(selectedModelID: "custom/model"))
        XCTAssertEqual(DefaultSpeechModel.isPreferred(selectedModelID: DefaultSpeechModel.identifier), DefaultSpeechModel.isSupported)
    }
